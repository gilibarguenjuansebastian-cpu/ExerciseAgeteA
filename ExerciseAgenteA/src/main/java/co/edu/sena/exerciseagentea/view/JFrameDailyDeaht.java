    public  void fillTable() {
        try {
            DefaultTableModel model = new DefaultTableModel();
            jTableRegister.setModel(model);
            //columnas
            model.addColumn("Id");
            model.addColumn("Numero de muertes");
            model.addColumn("Feccha de registro");
            model.addColumn("Hora de registro");
            model.addColumn("Usuario");
            model.addColumn("Codigo de registro");
            model.addColumn("Observaciones");
            //filas
            
            String[] row = new String[7];
            DateTimeFormatter timeFormat = DateTimeFormatter.ofPattern("HH:mm:ss");
            for (DailyDeath dailyDeath : dailyDeathsController.findAll()) {
                row[0] = String.valueOf(dailyDeath.getId());
                row[1] = String.valueOf(dailyDeath.getDeaths());
                row[2] = String.valueOf(dailyDeath.getDate());
                row[3] = dailyDeath.getTime().format(timeFormat);
                row[4] = dailyDeath.getUser();
                row[5] = dailyDeath.getCode();
                row[6] = dailyDeath.getObservations();
                model.addRow(row);
            }
        } catch (Exception ex) {
            System.getLogger(JFrameDailyDeaht.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }

